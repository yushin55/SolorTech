export function GuidePanel({
  guideKey,
  where,
  title,
  onClose,
  onOpenHelp,
}: {
  guideKey: GuideKey;
  where: string;
  title: string;
  onClose: () => void;
  onOpenHelp: () => void;
}) {
  const panel = useRef<HTMLElement>(null);
  const body = useRef<HTMLDivElement>(null);
  const guide = GUIDES[guideKey];
  useEffect(() => {
    const opener = document.activeElement as HTMLElement | null;
    panel.current?.focus({ preventScroll: true });
    return () => opener?.focus({ preventScroll: true });
  }, []);
  useEffect(() => {
    if (body.current) body.current.scrollTop = 0;
  }, [guideKey]);
  return (
    <aside
      id="guide-panel"
      className="guide-panel"
      aria-label="도우미"
      tabIndex={-1}
      ref={panel}
      onKeyDown={(e) => {
        if (e.key === "Escape") onClose();
      }}
    >
      <header className="guide-head">
        <div>
          <span className="guide-where">{where}</span>
          <h2>{title}</h2>
        </div>
        <button className="close" aria-label="도우미 닫기" onClick={onClose}>
          ×
        </button>
      </header>
      <div className="guide-body" ref={body}>
        <section>
          <h3>이 화면에서 하는 일</h3>
          <p>{guide.summary}</p>
          {guide.readOnly && <p className="guide-readonly">입력할 항목이 없는 확인용 화면입니다.</p>}
        </section>
        {guide.steps && (
          <section>
            <h3>이렇게 진행하세요</h3>
            <ol className="guide-steps">
              {guide.steps.map((step, i) => (
                <li key={i}>{step}</li>
              ))}
            </ol>
          </section>
        )}
        {guide.groups?.map((group) => (
          <section key={group.heading}>
            <h3>{group.heading}</h3>
            <dl className="guide-items">
              {group.items.map(([name, text]) => (
                <div key={name}>
                  <dt>{name}</dt>
                  <dd>{text}</dd>
                </div>
              ))}
            </dl>
          </section>
        ))}
        {guide.tips && (
          <section>
            <h3>알아두세요</h3>
            <ul className="guide-tips">
              {guide.tips.map((tip, i) => (
                <li key={i}>{tip}</li>
              ))}
            </ul>
          </section>
        )}
        {guide.next && (
          <section>
            <h3>다음으로</h3>
            <p>{guide.next}</p>
          </section>
        )}
      </div>
      <footer className="guide-foot">
        <button className="link" onClick={onOpenHelp}>
          전체 흐름과 용어 보기
        </button>
      </footer>
    </aside>
  );
}
